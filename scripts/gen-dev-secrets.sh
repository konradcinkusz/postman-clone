#!/usr/bin/env bash
#
# gen-dev-secrets.sh — creates the local development secrets in .local-stack/secrets.env (gitignored).
#
# Writes two values: the RS256 signing key for authservice (an RSA 2048 PKCS#8 private key, base64
# encoded onto one line) and the 32-byte base64 key that encrypts secret environment variables
# (ADR-0006, read by EnvironmentsService from WP09). Nothing is printed. The file is created with
# mode 600 inside the gitignored .local-stack/ directory.
#
# Idempotent: an existing secrets.env is kept. Regenerating the signing key signs every user out, so
# delete the file on purpose to get new values.

set -euo pipefail

REPO_ROOT="$(git rev-parse --show-toplevel)"
STACK_DIR="${REPO_ROOT}/.local-stack"
SECRETS_FILE="${STACK_DIR}/secrets.env"
KEY_TMP="${STACK_DIR}/.jwt-signing-key.pem.tmp"

mkdir -p "${STACK_DIR}"
chmod 700 "${STACK_DIR}"

if [ -f "${SECRETS_FILE}" ]; then
  echo "Kept existing ${SECRETS_FILE} (delete it to regenerate; that signs every user out)."
  exit 0
fi

umask 077
trap 'rm -f "${KEY_TMP}"' EXIT

openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 -out "${KEY_TMP}" 2>/dev/null
signing_key_b64="$(base64 < "${KEY_TMP}" | tr -d '\n')"
encryption_key="$(openssl rand -base64 32 | tr -d '\n')"

{
  echo "# Local development secrets. Generated by scripts/gen-dev-secrets.sh. Never commit this file."
  echo "JWT_PRIVATE_KEY_PEM_B64=${signing_key_b64}"
  echo "SECRETS_ENCRYPTION_KEY=${encryption_key}"
} > "${SECRETS_FILE}"

echo "Wrote ${SECRETS_FILE} (values not printed)."
